import { chromium } from '@playwright/test';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const browser = await chromium.launch({headless:true, ...(process.env.CHROME_PATH ? { executablePath:process.env.CHROME_PATH } : {})});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error') errors.push(m.text().slice(0,200))});
for (const file of fs.readdirSync('design/screens').filter(f=>f.endsWith('.html')&&!['SideNav.dc.html','TopBar.dc.html','TimePicker.dc.html'].includes(f))) {
 const route=file.replace('.dc.html','');
 await page.goto('http://127.0.0.1:5173/?screen='+route+'#'+route);
 await page.waitForTimeout(150);
 const failed=await page.getByText('화면을 불러오지 못했습니다', {exact:true}).count();
 console.log(route, failed?'FAILED':'OK');
 if(failed) errors.push(route+': error boundary');
}
await page.goto('http://127.0.0.1:5173/#B1-Overview');
await page.screenshot({path:'/private/tmp/sentrix-overview.png',fullPage:true});
await page.getByRole('link', {name:'원인 분석 보기'}).click();
await page.waitForURL('**/#B4-Incident');
await page.getByRole('button', {name:'프로필 메뉴'}).click();
await page.getByRole('menuitem', {name:/테마/}).click();
assert.equal(await page.locator('.g').getAttribute('data-theme'), 'dark');
await page.reload();
assert.equal(await page.locator('.g').getAttribute('data-theme'), 'dark');
await page.goto('http://127.0.0.1:5173/?check=filter#B3-Incidents');
await page.getByPlaceholder('장애 검색').fill('no-matching-incident');
assert.equal(await page.locator('main a[href="B4-Incident.dc.html"]').count(), 0);
await page.getByPlaceholder('장애 검색').fill('');
assert.ok(await page.locator('main a[href="B4-Incident.dc.html"]').count() > 0);
await page.setViewportSize({width:390,height:844});
await page.goto('http://127.0.0.1:5173/?check=mobile#B1-Overview');
await page.screenshot({path:'/private/tmp/sentrix-mobile.png',fullPage:true});
assert.ok(await page.getByRole('heading', {name:'개요',exact:true}).isVisible());
assert.equal(await page.getByRole('navigation', {name:'주 메뉴'}).count(), 0);
await page.getByRole('button', {name:'메뉴 열기 또는 닫기'}).click();
assert.ok(await page.getByRole('navigation', {name:'주 메뉴'}).isVisible());
assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
console.log('Navigation, theme persistence, incident search and mobile: OK');
await browser.close();
console.log(JSON.stringify(errors,null,2));
if(errors.length) process.exitCode=1;
